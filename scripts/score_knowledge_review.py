"""Score private human annotations against the same locally stored index.

This is a sampled-index quality report, not browser or live-cloud acceptance.
No model is called and no human labels are generated by this tool.
"""

import argparse
import json
import os

from prepare_knowledge_review import MAX_PACKET_BYTES, score_review_data


def read_packet(path):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(fd, "rb") as stream:
        contents = stream.read(MAX_PACKET_BYTES + 1)
    if len(contents) > MAX_PACKET_BYTES:
        raise ValueError("review_packet_size_limit")
    return json.loads(contents)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", required=True)
    parser.add_argument("--cases", required=True)
    parser.add_argument("--reviewed", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    report = score_review_data(args.workspace, read_packet(args.cases), read_packet(args.reviewed))
    fd = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "w") as stream:
        json.dump(report, stream, indent=2, ensure_ascii=False)
    print("Private sampled-index report created; no model requests were sent.")


if __name__ == "__main__":
    main()
